-- Supabase SQL Editor keessatti guutuu isaa raawwadhu.
-- Kutaan kun kutaa hoteelaa fi booking keessummootaa qopheessa.

create extension if not exists btree_gist;

create table if not exists public.rooms (
  id bigint generated by default as identity primary key,
  room_number text not null unique,
  room_type text not null,
  description text,
  capacity integer not null default 2 check (capacity > 0),
  price_per_night numeric(10,2) not null check (price_per_night >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  room_id bigint not null references public.rooms(id),
  guest_id uuid references auth.users(id) on delete cascade,
  guest_name text not null,
  guest_phone text,
  check_in date not null,
  check_out date not null,
  guests_count integer not null default 1 check (guests_count > 0),
  status text not null default 'pending'
    check (status in ('pending', 'confirmed', 'cancelled', 'completed')),
  special_request text,
  created_at timestamptz not null default now(),
  check (check_out > check_in),
  exclude using gist (
    room_id with =,
    daterange(check_in, check_out, '[)') with &&
  ) where (status in ('pending', 'confirmed'))
);

create table if not exists public.employees (
  id bigint generated by default as identity primary key,
  full_name text not null,
  email text not null unique,
  phone text,
  job_title text not null,
  status text not null default 'active' check (status in ('active', 'inactive')),
  created_at timestamptz not null default now()
);

alter table public.rooms enable row level security;
alter table public.bookings enable row level security;
alter table public.employees enable row level security;

-- Namni hundi kutaa hojiirra jiru ilaalu danda'a.
drop policy if exists "Anyone can view active rooms" on public.rooms;
create policy "Anyone can view active rooms"
  on public.rooms for select
  using (is_active = true);

-- Keessummaan booking isaa qofa ilaala, galmeessa, ykn yoo pending ta'e haqa.
drop policy if exists "Guests can view own bookings" on public.bookings;
create policy "Guests can view own bookings"
  on public.bookings for select to authenticated
  using ((select auth.uid()) = guest_id);

drop policy if exists "Guests can create own bookings" on public.bookings;
create policy "Guests can create own bookings"
  on public.bookings for insert to authenticated
  with check ((select auth.uid()) = guest_id and status = 'pending');

drop policy if exists "Guests can cancel own pending bookings" on public.bookings;
create policy "Guests can cancel own pending bookings"
  on public.bookings for update to authenticated
  using ((select auth.uid()) = guest_id and status = 'pending')
  with check ((select auth.uid()) = guest_id and status = 'cancelled');

-- Keessummaan account/password malee booking gochuu danda'a.
-- SQL kana duraan raawwatte ta'us, migration kun guest_id nullable taasisa.
alter table public.bookings alter column guest_id drop not null;
drop policy if exists "Anonymous guests can create bookings" on public.bookings;
create policy "Anonymous guests can create bookings"
  on public.bookings for insert to anon
  with check (guest_id is null and status = 'pending');

create index if not exists bookings_guest_id_idx on public.bookings (guest_id);
create index if not exists bookings_room_dates_idx on public.bookings (room_id, check_in, check_out);

-- Mirga REST API: kutaalee ilaali; keessummaan booking qofa erga.
grant select on public.rooms to anon, authenticated;
grant insert on public.bookings to anon;
grant select, insert, update on public.bookings to authenticated;
grant usage, select on sequence public.bookings_id_seq to anon, authenticated;
revoke all on public.employees from anon, authenticated;

